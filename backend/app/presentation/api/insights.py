"""Insight engine: the portal's "datos inteligentes" that publish themselves.

GET /api/insights/feed  ->  { insights: [...], updatedAt }   (cached 10 min)

For the most relevant matches of today/tomorrow (any followed league, not
only the Champions) it builds:
  - preview ("Antesala"): form of both teams, goals for/against, table
    position and what a win/draw means under that competition's format,
    head-to-head when ESPN has it, market probabilities.
  - impact (finished today): how the result leaves the table.
Every sentence is computed from ESPN numbers; nothing is generated by a model.
The same payload carries the raw data so the portal can open a detail modal.

It also opens a "¿Quién gana?" poll for the top upcoming matches (idempotent,
closes at kickoff) so the feed has fresh interaction every day.
"""
