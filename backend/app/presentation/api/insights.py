# ---------------------------------------------------------------- pure helpers

def _plural(n: int, one: str, many: str) -> str:
    return f"{n} {one if n == 1 else many}"


def form_of(events: list[dict]) -> dict:
    """lastFiveGames events -> {results: 'WWDLW', w, d, l, gf, ga} (from the team's point of view)."""
    res = "".join((e.get("gameResult") or "")[:1].upper() for e in events if e.get("gameResult"))
    gf = ga = 0
    for e in events:
        parts = str(e.get("score") or "").split("-")
        if len(parts) != 2 or not all(p.strip().isdigit() for p in parts):
            continue
        hi, lo = sorted((int(parts[0]), int(parts[1])), reverse=True)
        # ESPN writes the score winner-first ("4-0" in a defeat): orient it by the result
        result = (e.get("gameResult") or "").upper()[:1]
        gf, ga = (gf + lo, ga + hi) if result == "L" else (gf + hi, ga + lo)
    return {"results": res, "w": res.count("W"), "d": res.count("D"), "l": res.count("L"), "gf": gf, "ga": ga}


def form_sentence(name: str, f: dict) -> str | None:
    n = len(f["results"])
    if not n:
        return None
    if f["w"] >= 4:
        lead = f"{name} llega en racha: ganó {f['w']} de sus últimos {n}"
    elif f["l"] >= 3:
        lead = f"{name} llega golpeado: perdió {f['l']} de sus últimos {n}"
    elif f["w"] == 0:
        lead = f"{name} no gana en sus últimos {n} ({_plural(f['d'], 'empate', 'empates')} y {_plural(f['l'], 'derrota', 'derrotas')})"
    else:
        lead = f"{name}: {f['w']}G {f['d']}E {f['l']}P en sus últimos {n}"
    return f"{lead}, con {f['gf']} goles a favor y {f['ga']} en contra."


def table_rows(summary: dict) -> list[dict]:
    groups = ((summary.get("standings") or {}).get("groups") or [])
    for g in groups:
        entries = ((g.get("standings") or {}).get("entries") or [])
        if entries:
            rows = []
            for i, e in enumerate(entries):
                stats = {s.get("name"): s.get("value") for s in e.get("stats") or []}
                rows.append({"pos": i + 1, "teamId": str(e.get("id") or ""), "team": e.get("team") or "",
                             "points": int(stats.get("points") or 0), "played": int(stats.get("gamesPlayed") or 0),
                             "gd": int(stats.get("pointDifferential") or 0)})
            return rows
    return []


def zone_for(league: str, pos: int) -> str | None:
    fmt = format_for(league)
    if fmt and fmt.kind == "fase-de-liga":
        return "octavos directos" if pos <= 8 else "playoff" if pos <= 24 else "eliminación"
    return None


def table_sentence(league: str, rows: list[dict], team_id: str, name: str) -> str | None:
    me = next((r for r in rows if r["teamId"] == team_id), None)
    if not me:
        return None
    fmt = format_for(league)
    text = f"{name} es {me['pos']}.º con {_plural(me['points'], 'punto', 'puntos')}"
    zone = zone_for(league, me["pos"])
    if zone:
        text += f" (zona de {zone})"
    if fmt and fmt.kind == "fase-de-liga" and len(rows) >= 24:
        cut8, cut24 = rows[7]["points"], rows[23]["points"]
        if me["pos"] > 8 and me["points"] + 3 >= cut8:
            text += "; una victoria lo mete en la pelea por los octavos directos"
        elif me["pos"] > 24 and me["points"] + 3 >= cut24:
            text += "; con un triunfo alcanza la zona de playoff"
    elif me["pos"] > 1 and rows:
        gap = rows[0]["points"] - me["points"]
        if 0 < gap <= 3:
            text += f"; está a {_plural(gap, 'punto', 'puntos')} del líder"
    return text + "."


def market_probs(summary: dict) -> dict | None:
    pc = (summary.get("pickcenter") or [None])[0]
    if not pc:
        return None
    dec = {"home": american_to_decimal((pc.get("homeTeamOdds") or {}).get("moneyLine")),
           "away": american_to_decimal((pc.get("awayTeamOdds") or {}).get("moneyLine")),
           "draw": american_to_decimal((pc.get("drawOdds") or {}).get("moneyLine"))}
    if not all(dec.values()):
        return None
    p = no_vig({k: v for k, v in dec.items() if v})
    return {k: round(v * 100) for k, v in p.items()}


def h2h_of(summary: dict, home_id: str) -> list[dict]:
    out = []
    for block in summary.get("headToHeadGames") or []:
        if str((block.get("team") or {}).get("id")) != home_id:
            continue
        for e in block.get("events") or []:
            out.append({"date": (e.get("gameDate") or "")[:10], "result": (e.get("gameResult") or "").upper(),
                        "score": e.get("score") or f"{e.get('homeTeamScore', '')}-{e.get('awayTeamScore', '')}",
                        "competition": e.get("leagueName") or ""})
    return out[:10]


def h2h_sentence(home: str, away: str, games: list[dict]) -> str | None:
    if not games:
        return None
    w = sum(1 for g in games if g["result"] == "W")
    d = sum(1 for g in games if g["result"] == "D")
    l_ = sum(1 for g in games if g["result"] == "L")
    return f"Historial reciente: {home} {w} victorias, {d} empates y {away} {l_} victorias en {len(games)} cruces."


def _teams(summary: dict) -> tuple[dict, dict, dict] | None:
    comp = ((summary.get("header") or {}).get("competitions") or [{}])[0]
    teams = {c.get("homeAway"): c for c in comp.get("competitors") or []}
    if "home" not in teams or "away" not in teams:
        return None
    return comp, teams["home"], teams["away"]


def _team_out(c: dict, form: dict | None, rows: list[dict]) -> dict:
    t = c.get("team") or {}
    tid = str(t.get("id") or "")
    row = next((r for r in rows if r["teamId"] == tid), None)
    logos = t.get("logos") or []
    return {"id": tid, "name": t.get("displayName") or "", "short": t.get("abbreviation") or "",
            "logo": logos[0].get("href") if logos else t.get("logo"), "score": c.get("score"),
            "form": form["results"] if form else None, "position": row["pos"] if row else None,
            "points": row["points"] if row else None}


def _neighbors(rows: list[dict], ids: set[str]) -> list[dict]:
    keep: set[int] = set()
    for r in rows:
        if r["teamId"] in ids:
            keep.update(range(max(0, r["pos"] - 3), min(len(rows), r["pos"] + 2)))
    return [{**rows[i], "highlight": rows[i]["teamId"] in ids} for i in sorted(keep)]


CLASICOS = [
    {"millonarios", "santa fe"}, {"atlético nacional", "independiente medellín"}, {"américa de cali", "deportivo cali"},
    {"junior", "unión magdalena"}, {"real madrid", "barcelona"}, {"real madrid", "atlético madrid"}, {"barcelona", "espanyol"},
    {"manchester united", "manchester city"}, {"liverpool", "everton"}, {"arsenal", "tottenham hotspur"}, {"liverpool", "manchester united"},
    {"internazionale", "ac milan"}, {"juventus", "internazionale"}, {"as roma", "lazio"}, {"bayern munich", "borussia dortmund"},
    {"boca juniors", "river plate"}, {"flamengo", "fluminense"}, {"paris saint-germain", "marseille"}, {"celtic", "rangers"},
]


def _key(name: str) -> str:
    return (name or "").lower().replace("fc ", "").strip()


def favorite_of(market: dict | None) -> dict:
    if not market:
        return {"side": None, "label": None, "probability": None}
    side = max(("home", "away"), key=lambda k: market[k])
    p_ = market[side]
    if p_ >= 60:
        return {"side": side, "label": "Favorito claro", "probability": p_}
    if p_ >= 45:
        return {"side": side, "label": "Ligero favorito", "probability": p_}
    return {"side": None, "label": "Partido parejo", "probability": p_}


def key_players(summary: dict, home_id: str) -> list[dict]:
    """Top scorer (and top assister if different) of each team in this competition, from ESPN leaders."""
    out = []
    for block in summary.get("leaders") or []:
        team_id = str((block.get("team") or {}).get("id") or "")
        side = "home" if team_id == home_id else "away"
        picked: set[str] = set()
        for cat in block.get("leaders") or []:
            name = cat.get("name")
            if name not in ("goalsLeaders", "assistsLeaders"):
                continue
            top = (cat.get("leaders") or [None])[0]
            if not top:
                continue
            athlete = top.get("athlete") or {}
            aid = str(athlete.get("id") or "")
            value = top.get("displayValue") or ""
            num = value.split(":")[-1].strip() if ":" in value else value
            if not aid or aid in picked or not num or num == "0":
                continue
            picked.add(aid)
            unit = "goles" if name == "goalsLeaders" else "asistencias"
            if num == "1":
                unit = unit[:-2] if unit == "goles" else unit[:-1]
            out.append({"id": aid, "name": athlete.get("displayName") or "", "team": side,
                        "headshot": (athlete.get("headshot") or {}).get("href"),
                        "stat": f"{num} {unit} en esta competición"})
    return out[:4]


def story_of(league: str, home: dict, away: dict, forms: dict, market: dict | None) -> str | None:
    if {_key(home["name"]), _key(away["name"])} in CLASICOS:
        return "clasico"
    hp, ap = home.get("position"), away.get("position")
    fmt = format_for(league)
    top = 8 if fmt and fmt.kind == "fase-de-liga" else 4
    if hp and ap and hp <= top and ap <= top:
        return "duelo-de-lideres"
    if market and max(market["home"], market["away"]) >= 75:
        return "david-vs-goliat"
    if hp and ap and abs(hp - ap) >= 15:
        return "david-vs-goliat"
    if any(f["w"] >= 4 for f in forms.values()):
        return "en-racha"
    if hp and ap:
        bottom = (fmt.teams or 20) - 3 if fmt and fmt.teams else 17
        low = 24 if fmt and fmt.kind == "fase-de-liga" else bottom
        if hp > low and ap > low:
            return "necesitados"
    return None


def kickoff_local(iso: str | None) -> str | None:
    if not iso:
        return None
    try:
        when = datetime.fromisoformat(iso.replace("Z", "+00:00")).astimezone(timezone(timedelta(hours=-5)))
    except ValueError:
        return None
    return when.strftime("%H:%M")


def build_preview(summary: dict, league: str) -> dict | None:
    parts = _teams(summary)
    if not parts:
        return None
    comp, home, away = parts
    rows = table_rows(summary)
    forms = {str((b.get("team") or {}).get("id")): form_of(b.get("events") or []) for b in summary.get("lastFiveGames") or []}
    hid, aid = str((home.get("team") or {}).get("id")), str((away.get("team") or {}).get("id"))
    hn, an = (home.get("team") or {}).get("displayName") or "", (away.get("team") or {}).get("displayName") or ""
    market = market_probs(summary)
    h2h = h2h_of(summary, hid)
    facts = [s for s in (
        form_sentence(hn, forms[hid]) if hid in forms else None,
        form_sentence(an, forms[aid]) if aid in forms else None,
        table_sentence(league, rows, hid, hn), table_sentence(league, rows, aid, an),
        h2h_sentence(hn, an, h2h),
    ) if s]
    if market:
        fav = max(("home", "away"), key=lambda k: market[k])
        fav_name = hn if fav == "home" else an
        facts.append(f"El mercado da {market[fav]}% a {fav_name}, {market['draw']}% al empate.")
    if not facts:
        return None
    fmt = format_for(league)
    out_base = {
        "id": f"preview:{comp.get('id')}", "kind": "preview", "league": league, "leagueName": LEAGUE_NAMES.get(league, league),
        "matchId": str(comp.get("id")), "kickoff": comp.get("date"), "state": "pre",
        "headline": f"Antesala: {hn} vs {an}", "facts": facts,
        "home": _team_out(home, forms.get(hid), rows), "away": _team_out(away, forms.get(aid), rows),
        "market": market, "h2h": h2h, "standings": _neighbors(rows, {hid, aid}),
        "format": fmt.summary if fmt else None,
    }
    out = {**out_base, "phase": "previa", "kickoffLocal": kickoff_local(comp.get("date")), "favorite": favorite_of(market),
           "keyPlayers": key_players(summary, hid)}
    out["story"] = story_of(league, out["home"], out["away"], forms, market)
    return out


def build_impact(summary: dict, league: str) -> dict | None:
    parts = _teams(summary)
    if not parts:
        return None
    comp, home, away = parts
    rows = table_rows(summary)
    hn, an = (home.get("team") or {}).get("displayName") or "", (away.get("team") or {}).get("displayName") or ""
    try:
        hs, as_ = int(home.get("score")), int(away.get("score"))
    except (TypeError, ValueError):
        return None
    hid, aid = str((home.get("team") or {}).get("id")), str((away.get("team") or {}).get("id"))
    facts = [s for s in (table_sentence(league, rows, hid, hn), table_sentence(league, rows, aid, an)) if s]
    if not facts:
        return None
    verdict = f"{hn} {hs}-{as_} {an}"
    return {
        "id": f"impact:{comp.get('id')}", "kind": "impact", "league": league, "leagueName": LEAGUE_NAMES.get(league, league),
        "matchId": str(comp.get("id")), "kickoff": comp.get("date"), "state": "post",
        "headline": f"{verdict}: así queda la tabla", "facts": facts,
        "home": _team_out(home, None, rows), "away": _team_out(away, None, rows),
        "market": None, "h2h": [], "standings": _neighbors(rows, {hid, aid}), "format": None,
        "phase": "final", "kickoffLocal": kickoff_local(comp.get("date")), "favorite": favorite_of(None), "keyPlayers": [], "story": None,
    }


def match_score(league: str, event: dict) -> float:
    """Ranking for which matches deserve an insight: league weight + live/soon bonus."""
    base = LEAGUE_WEIGHT.get(league, 5)
    try:
        start = datetime.fromisoformat(str(event.get("date")).replace("Z", "+00:00"))
        hours = (start - datetime.now(timezone.utc)).total_seconds() / 3600
        base += max(0.0, 3 - abs(hours) / 6)  # closer kickoffs first
    except ValueError:
        pass
    return base


def diverse(ranked: list[tuple[str, dict]], limit: int, per_league: int) -> list[tuple[str, dict]]:
    """Best-ranked matches, at most `per_league` from the same competition (not only the Champions)."""
    out: list[tuple[str, dict]] = []
    counts: dict[str, int] = {}
    for league, event in ranked:
        if counts.get(league, 0) < per_league:
            out.append((league, event))
            counts[league] = counts.get(league, 0) + 1
        if len(out) >= limit:
            break
    return out


# ---------------------------------------------------------------- I/O

async def _events(client: httpx.AsyncClient, league: str, day: str) -> list[tuple[str, dict]]:
    try:
        res = await client.get(_SCOREBOARD.format(league=league), params={"dates": day})
        return [(league, e) for e in (res.json().get("events") or [])] if res.status_code == 200 else []
    except (httpx.HTTPError, ValueError):
        return []


async def _summary(client: httpx.AsyncClient, league: str, event_id: str) -> dict | None:
    try:
        res = await client.get(_SUMMARY.format(league=league), params={"event": event_id})
        return res.json() if res.status_code == 200 else None
    except (httpx.HTTPError, ValueError):
        return None


def _ensure_polls(container: Container, previews: list[dict]) -> None:
    """One "¿Quién gana?" poll per top upcoming match, closing at kickoff (idempotent by news_id)."""
    global _last_polls
    if time.monotonic() - _last_polls < 900:
        return
    _last_polls = time.monotonic()
    try:
        client = container.news_repo._client
        for p in previews[:3]:
            key = f"match:{p['league']}:{p['matchId']}"
            if client.table("polls").select("id").eq("news_id", key).limit(1).execute().data:
                continue
            poll = client.table("polls").insert({
                "kind": "poll", "question": f"¿Quién gana {p['home']['name']} vs {p['away']['name']}?",
                "context": f"{p['leagueName']} · se cierra al inicio del partido.", "status": "open",
                "closes_at": p["kickoff"], "news_id": key, "featured": False, "placement": ["pulse"],
            }).execute().data[0]
            client.table("poll_options").insert([
                {"poll_id": poll["id"], "label": p["home"]["name"], "position": 0},
                {"poll_id": poll["id"], "label": "Empate", "position": 1},
                {"poll_id": poll["id"], "label": p["away"]["name"], "position": 2},
            ]).execute()
    except Exception as exc:  # noqa: BLE001 -- polls are a bonus; never break the feed
        log.warning("auto_polls_failed: %s", exc)


@router.get("/feed")
async def insights_feed(response: Response, container: Container = Depends(get_container)) -> dict:
    hit = _cache.get("feed")
    if hit and time.monotonic() - hit[0] < _TTL:
        payload = hit[1]
    else:
        now = datetime.now(timezone.utc) - timedelta(hours=5)  # Colombia's calendar day
        days = [now.strftime("%Y%m%d"), (now + timedelta(days=1)).strftime("%Y%m%d")]
        async with httpx.AsyncClient(timeout=httpx.Timeout(8.0)) as client:
            groups = await asyncio.gather(*(_events(client, lg, d) for lg in LEAGUE_WEIGHT for d in days))
            seen: set[str] = set()
            events = []
            for league, e in (x for g in groups for x in g):
                if e.get("id") in seen:
                    continue
                seen.add(e.get("id"))
                events.append((league, e))
            state = lambda e: ((e.get("status") or {}).get("type") or {}).get("state")  # noqa: E731
            pre = diverse(sorted((x for x in events if state(x[1]) == "pre"), key=lambda x: -match_score(*x)), 10, 3)
            post = diverse(sorted((x for x in events if state(x[1]) == "post"), key=lambda x: -LEAGUE_WEIGHT.get(x[0], 5)), 6, 2)
            sums = await asyncio.gather(*(_summary(client, lg, str(e.get("id"))) for lg, e in pre + post))
        previews = [p for (lg, _), s in zip(pre, sums[:len(pre)]) if s and (p := build_preview(s, lg))]
        impacts = [p for (lg, _), s in zip(post, sums[len(pre):]) if s and (p := build_impact(s, lg))]
        payload = {"insights": previews + impacts, "updatedAt": datetime.now(timezone.utc).isoformat()}
        _cache["feed"] = (time.monotonic(), payload)
        if previews:
            await asyncio.to_thread(_ensure_polls, container, previews)
    response.headers["Cache-Control"] = "public, max-age=120"
    return payload
